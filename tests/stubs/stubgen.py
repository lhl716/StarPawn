"""Iteratively grow permissive type stubs so source/Game can be type-checked without the game.
Members default to `dynamic`; this checks syntax/our own types, NOT real game signatures."""
import re, subprocess, sys, collections, json, os
ROOT='/home/user/StarPawn'; DN='/opt/dn'
OUT=ROOT+'/tests/stubs/GameStubs.generated.cs'
manual=open(ROOT+'/tests/stubs/manual.cs.txt').read() if os.path.exists(ROOT+'/tests/stubs/manual.cs.txt') else ''
types=collections.OrderedDict()   # (ns,name) -> {'static':bool,'members':{name:kind}}
state_file=ROOT+'/tests/stubs/stubstate.json'
if os.path.exists(state_file):
    for k,v in json.load(open(state_file)).items(): types[tuple(k.split('|'))]=v
def render():
    by=collections.defaultdict(list)
    for (ns,name),t in types.items(): by[ns].append((name,t))
    out=['// GENERATED by tests stub generator. Permissive stand-ins, NOT the game API.','#pragma warning disable','using System;']
    for ns,items in by.items():
        if ns: out.append('namespace %s {'%ns)
        for name,t in items:
            out.append('public partial class %s {'%name)
            if name not in manual_names: out.append(' public %s(params object[] a){}'%name)
            for m,kind in t['members'].items():
                if re.search(r'\b%s\b'%m, manual_member_text.get(name,'')): continue
                out.append(' public %sdynamic %s;'%('static ' if kind=='static' else '',m))
            out.append('}')
        if ns: out.append('}')
    open(OUT,'w').write('\n'.join(out)+'\n')
manual_names=set(re.findall(r'class (\w+)',manual))
_parts=re.split(r'(?=\bclass \w+)',manual)
manual_member_text={}
for _p in _parts:
    _m=re.match(r'class (\w+)',_p)
    if _m: manual_member_text[_m.group(1)]=manual_member_text.get(_m.group(1),'')+_p[len(_m.group(0)):]
env=dict(os.environ,DOTNET_ROOT=DN+'/sdk')
refs=['-r:'+f for f in sorted(__import__('glob').glob(DN+'/x/microsoft.netcore.app.ref/ref/net8.0/*.dll'))]
for it in range(60):
    render()
    open(ROOT+'/tests/stubs/Manual.cs','w').write(manual)
    files=sorted(__import__('glob').glob(ROOT+'/source/Core/*.cs')+__import__('glob').glob(ROOT+'/source/Game/*.cs'))+[OUT,ROOT+'/tests/stubs/Manual.cs']
    p=subprocess.run([DN+'/sdk/dotnet',DN+'/x/toolset/tasks/netcore/bincore/csc.dll','-nologo','-target:library','-nostdlib+','-langversion:8.0','-nullable:enable','-nowarn:CS1701,CS8632,CS0618']+refs+['-r:'+DN+'/x/nj/lib/netstandard2.0/Newtonsoft.Json.dll','-r:'+DN+'/x/harmony/lib/net48/0Harmony.dll','-out:/tmp/gstub.dll']+files,capture_output=True,text=True,env=env)
    errs=[l for l in p.stdout.splitlines() if ': error ' in l]
    changed=False
    for l in errs:
        m=re.search(r"error CS0246: The type or namespace name '(\w+)'",l)
        if m and ('',m.group(1)) not in types and ('',m.group(1)) not in types: types[('',m.group(1))]={'members':{}}; changed=True; continue
        m=re.search(r"error CS0234: The type or namespace name '(\w+)' does not exist in the namespace '([\w.]+)'",l)
        if m and (m.group(2),m.group(1)) not in types: types[(m.group(2),m.group(1))]={'members':{}}; changed=True; continue
        m=re.search(r"error CS0103: The name '(\w+)' does not exist",l)
        if m and m.group(1)[0].isupper() and ('',m.group(1)) not in types and m.group(1) not in manual_names: types[('',m.group(1))]={'members':{}}; changed=True; continue
        m=re.search(r"error CS(1061|0117): '([\w.]+)' does not contain a definition for '(\w+)'",l)
        if m:
            full=m.group(2); ns,name=(full.rsplit('.',1) if '.' in full else ('',full))
            key=(ns,name)
            if key in types and m.group(3) not in types[key]['members']:
                types[key]['members'][m.group(3)]='static' if m.group(1)=='0117' else 'inst'; changed=True
    json.dump({'|'.join(k):v for k,v in types.items()},open(state_file,'w'),indent=0)
    if not changed:
        print('\n'.join(errs[:60])); print('ERRORS',len(errs),'iterations',it); break
